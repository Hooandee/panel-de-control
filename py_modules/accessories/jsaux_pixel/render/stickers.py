def frames_of(sticker: str) -> tuple[tuple[str, ...], ...]:
    return STICKERS[sticker]


def sprite(sticker: str, frame: int, scale: int = 1, tint: tuple[int, int, int] | None = None) -> Canvas:
    rows = STICKERS[sticker][frame % len(STICKERS[sticker])]
    width = max(len(row) for row in rows)
    canvas = Canvas(width * scale, len(rows) * scale)
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell in PALETTE:
                rgb = PALETTE[cell]
                if tint is not None and cell not in ("K", "W"):
                    rgb = tint
                canvas.rect(x * scale, y * scale, scale, scale, rgb)
    return canvas
